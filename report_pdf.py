def _comments_table(record, cell):
    comments = record.get("comments") or NO_COMMENTS

    comments_table = Table(
        [[cell(comments)]],
        colWidths=[REPORT_WIDTH],
        rowHeights=[COMMENTS_HEIGHT]
    )

    comments_table.setStyle(TableStyle([
        ("BOX", (0, 0), (-1, -1), 0.5, colors.grey),
        ("LEFTPADDING", (0, 0), (-1, -1), COMMENTS_PADDING),
        ("RIGHTPADDING", (0, 0), (-1, -1), COMMENTS_PADDING),
        ("TOPPADDING", (0, 0), (-1, -1), COMMENTS_PADDING),
        ("BOTTOMPADDING", (0, 0), (-1, -1), COMMENTS_PADDING),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BACKGROUND", (0, 0), (-1, -1), RESULT_BG)
    ]))
    return comments_table


def _photos_table(record, cell):
    photo_cells = []

    photos = record.get("photos", [])

    for index in range(3):
        if index < 2:
            filename = (
                photos[index]
                if index < len(photos)
                else ""
            )
        else:
            filename = record.get("horizontal_photo", "")

        if filename and Path(filename).is_file():
            photo = Image(filename)

            if index < 2:
                photo._restrictSize(85 * mm, 85 * mm)
            else:
                photo._restrictSize(170 * mm, 85 * mm)

            photo.hAlign = "CENTER"
            photo_cells.append(photo)
        else:
            photo_cells.append(cell("No photograph supplied"))

    photos_table = Table(
        [[photo_cells[0], photo_cells[1]], [photo_cells[2], ""]],
        colWidths=[90 * mm, 90 * mm],
        rowHeights=[90 * mm, 90 * mm]
    )

    photos_table.setStyle(TableStyle([
        ("SPAN", (0, 1), (1, 1)),
        ("BOX", (0, 0), (0, 0), 0.5, colors.grey),
        ("BOX", (1, 0), (1, 0), 0.5, colors.grey),
        ("BOX", (0, 1), (1, 1), 0.5, colors.grey),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4)
    ]))
    return photos_table


def _draw_footer(canvas, document, shared, record):
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(colors.grey)

    canvas.drawString(
        14 * mm,
        7 * mm,
        "Metroscan Hydrant Test Report | " + str(shared.get("job", "")).strip()
        + " | "
        + str(record.get("ref", ""))
    )

    canvas.drawRightString(A4[0] - 14 * mm, 7 * mm, f'Page {document.page}')

    canvas.setFont("Helvetica", 6)
    canvas.setFillColor(colors.HexColor("#B0B0B0"))
    canvas.drawCentredString(A4[0] / 2, 3.5 * mm, PDF_COPYRIGHT)

    canvas.restoreState()


def build_pdf(shared, record, output_file):
    """Render one inspection using the report's two-page layout."""
    if not comments_layout(record.get("comments", ""))[0]:
        raise ValueError("Comments exceed the available PDF comment box.")
    document = SimpleDocTemplate(
        str(output_file),
        pagesize=A4,
        rightMargin=14 * mm,
        leftMargin=14 * mm,
        topMargin=12 * mm,
        bottomMargin=15 * mm,
        title=f"Hydrant Test Report - {record.get("ref", "")}"
    )

    styles, title_style, section_style, cell_style = _report_styles()

    def cell(value):
        text_value = str(value or "—")
        safe_value = escape(text_value).replace("\n", "<br/>")
        return Paragraph(safe_value, cell_style)

    story = []
    _append_header(story, record, styles, title_style, 75 * mm, 5)
    for heading, table in [
        ("INSPECTION DETAILS", _details_table(shared, record, cell)),
        ("INSPECTION CHECKLIST", _checklist_table(record, cell)),
        ("HYDRANT TEST RESULTS", _results_table(record, cell)),
        ("COMMENTS", _comments_table(record, cell)),
    ]:
        story.extend([Paragraph(heading, section_style), table])

    story.append(PageBreak())
    _append_header(story, record, styles, title_style, 50 * mm, 8)
    story.extend([Paragraph("PHOTOGRAPHS", section_style), _photos_table(record, cell)])
    footer = partial(_draw_footer, shared=shared, record=record)
    document.build(story, onFirstPage=footer, onLaterPages=footer)


def build_combined_pdf(shared, records, output_file):
    """Combine the current job's reports in their displayed order."""
    if not records:
        raise ValueError("Please add at least one hydrant.")

    writer = PdfWriter()
    try:
        with TemporaryDirectory() as folder:
            for index, record in enumerate(records, start=1):
                report_path = Path(folder) / f"{index}.pdf"
                build_pdf(shared, record, report_path)
                writer.append(str(report_path))
            writer.add_metadata({
                "/Title": f"Hydrant Test Reports - {shared.get('job', '')}",
            })
            with open(output_file, "wb") as output:
                writer.write(output)
    finally:
        writer.close()
