"""PDF layout and comment sizing. This module does not depend on Tkinter."""

from functools import partial
from pathlib import Path
from tempfile import TemporaryDirectory
from xml.sax.saxutils import escape

from pypdf import PdfWriter

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image, PageBreak,
)

from app_data import CHECKLIST

LOGO_PATH = Path(__file__).resolve().parent / "logo.png"
REPORT_WIDTH = 180 * mm
COMMENTS_HEIGHT = 50 * mm
COMMENTS_PADDING = 7
CELL_FONT_SIZE = 8
CELL_LEADING = 10
NO_COMMENTS = "No comments recorded."
PDF_COPYRIGHT = (
    "Generated by Hydrant Test Report Manager | © 2026 Erick L. Martins"
)
RESULT_BG = colors.Color(236 / 255, 245 / 255, 206 / 255, alpha=0.5)
HEADER_BG = colors.Color(148 / 255, 193 / 255, 34 / 255, alpha=0.5)


def comments_layout(value):
    """Measure text using the same font, width and padding as the PDF cell."""
    style = ParagraphStyle(
        "CommentsMeasurement",
        fontName="Helvetica",
        fontSize=CELL_FONT_SIZE,
        leading=CELL_LEADING,
    )
    text = escape(str(value or NO_COMMENTS)).replace("\n", "<br/>")
    paragraph = Paragraph(text, style)
    _, height = paragraph.wrap(REPORT_WIDTH - 2 * COMMENTS_PADDING, 1000000)
    return height <= COMMENTS_HEIGHT - 2 * COMMENTS_PADDING, height


def _append_header(story, record, styles, title_style, logo_height, gap):
    if LOGO_PATH.is_file():
        logo = Image(str(LOGO_PATH))
        logo._restrictSize(100 * mm, logo_height)

        logo_table = Table([[logo]], colWidths=[REPORT_WIDTH])

        logo_table.setStyle(TableStyle([
            ("ALIGN", (0, 0), (-1, -1), "CENTER"),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ]))

        story.append(logo_table)

    story.append(Paragraph("HYDRANT TEST REPORT", title_style))

    story.append(
        Paragraph(
            "Hydrant Reference: <b>" + escape(str(record.get("ref", "—"))) + "</b>",
            styles["Normal"]
        )
    )

    story.append(Spacer(1, gap))


def _report_styles():
    styles = getSampleStyleSheet()

    title_style = ParagraphStyle(
        "HydrantTitle",
        parent=styles["Title"],
        fontSize=17,
        leading=21,
        alignment=1,
        textColor=colors.HexColor("#284221"),
        spaceAfter=8
    )

    section_style = ParagraphStyle(
        "HydrantSection",
        parent=styles["Heading2"],
        fontSize=10,
        leading=13,
        textColor=colors.HexColor("#284221"),
        spaceBefore=9,
        spaceAfter=5
    )

    cell_style = ParagraphStyle(
        "HydrantCell",
        parent=styles["BodyText"],
        fontSize=CELL_FONT_SIZE,
        leading=CELL_LEADING
    )
    return styles, title_style, section_style, cell_style


def _details_table(shared, record, cell):
    detail_fields = [
        ("Job Number", "job", "Hydrant Type", "hydrant_type"),

        ("Site / Location", "location", "Next Inspection Due", "next_date"),

        ("Inspection Date", "inspection_date", "Depth (mm)", "depth"),

        ("Time", "time", "Testing Engineer", "engineer"),

        ("Client", "client", "Report Completed By", "completed_by")
    ]

    rows = []

    for label1, key1, label2, key2 in detail_fields:
        value1 = shared.get(key1, record.get(key1, ""))

        value2 = shared.get(key2, record.get(key2, ""))

        rows.append([cell(label1), cell(value1), cell(label2), cell(value2)])

    details_table = Table(rows, colWidths=[32 * mm, 53 * mm, 36 * mm, 59 * mm])

    details_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (0, -1), HEADER_BG),
        ("BACKGROUND", (2, 0), (2, -1), HEADER_BG),
        ("BACKGROUND", (1, 0), (1, -1), RESULT_BG),
        ("BACKGROUND", (3, 0), (3, -1), RESULT_BG),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 5),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6)
    ]))
    return details_table


def _checklist_table(record, cell):
    checklist_rows = [[cell("Inspection Item"), cell("Result")]]

    for key, label in CHECKLIST:
        checklist_rows.append([cell(label), cell(record.get(key, ""))])

    checklist_table = Table(checklist_rows, colWidths=[125 * mm, 55 * mm])

    checklist_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), HEADER_BG),
        ("BACKGROUND", (0, 1), (-1, -1), RESULT_BG),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5)
    ]))
    return checklist_table


